def seed_quiz():
    db: Session = SessionLocal()
    try:
        quiz_id = str(uuid.uuid4())
        now = datetime.now(timezone.utc)
        quiz = Quiz(
            id=quiz_id,
            title="اختبار لائحة كلية علوم الحاسب - جامعة بنها الأهلية",
            duration=20,
            course_code=None,
            college_id="computer_science",
            visibility="college",
            academic_year=None,
            term=None,
            section=None,
            start_time=None,
            end_time=None,
            questions_json=json.dumps(QUESTIONS, ensure_ascii=False),
            is_active=True,
            created_by=2,
            created_at=now,
        )
        db.add(quiz)
        db.commit()
        print(f"✅ Quiz created successfully!")
        print(f"   ID: {quiz_id}")
        print(f"   Title: {quiz.title}")
        print(f"   Questions: {len(QUESTIONS)}")
        print(f"   Duration: {quiz.duration} minutes")
    except Exception as e:
        db.rollback()
        print(f"❌ Error: {e}")
    finally:
        db.close()


if __name__ == "__main__":
    seed_quiz()
